#!/bin/sh
# Generate lib/entities.inc from the WHATWG entities.json.
# Usage: tools/gen-entities.sh [entities.json] > lib/entities.inc

url="https://html.spec.whatwg.org/entities.json"

if [ -n "$1" ]; then
	json="$1"
else
	json=$(mktemp)
	trap 'rm -f "$json"' EXIT
	wget -q -O "$json" "$url" || exit 1
fi

echo "/* Generated by tools/gen-entities.sh from $url */"
grep '"codepoints"' "$json" | LC_ALL=C sort | awk '
function utf8(c) {
	if (c < 128)
		return sprintf("\\x%02x", c)
	if (c < 2048)
		return sprintf("\\x%02x\\x%02x", 192 + int(c / 64), 128 + c % 64)
	if (c < 65536)
		return sprintf("\\x%02x\\x%02x\\x%02x", 224 + int(c / 4096),
			128 + int(c / 64) % 64, 128 + c % 64)
	return sprintf("\\x%02x\\x%02x\\x%02x\\x%02x", 240 + int(c / 262144),
		128 + int(c / 4096) % 64, 128 + int(c / 64) % 64, 128 + c % 64)
}
{
	name = $1
	gsub(/[":&]/, "", name)
	cps = $0
	sub(/.*\[/, "", cps)
	sub(/\].*/, "", cps)
	n = split(cps, cp, /, */)
	out = ""
	for (i = 1; i <= n; i++)
		out = out utf8(cp[i] + 0)
	printf "{ \"%s\", \"%s\" },\n", name, out
}'
